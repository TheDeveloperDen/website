import {
    quicktype,
    InputData,
    JSONSchemaInput,
    FetchingJSONSchemaStore
} from "quicktype-core";
import path from "path";
import fs from "fs"
import { $ } from "bun";

// What version of the LearningResources repo we're using
const REPO_URL = "https://cdn.jsdelivr.net/gh/TheDeveloperDen/LearningResources@94a95ce0bc8c0625e2af95b404d80f2224714b73/";
const SCHEMA_URL = REPO_URL + "openapi.schema.json";
const OUTPUT_DIR = path.join(__dirname, "./src");
const MODULE_NAME = "LearningResources";

async function generateElmTypes() {

    await $`bunx elm-open-api ${SCHEMA_URL} --output-dir ${OUTPUT_DIR} --module-name LearningResources`;

    // remove the generated Api.elm file since we only care about the types
    const apiFilePath = path.join(OUTPUT_DIR, "LearningResources/Api.elm");
    try {
        await fs.promises.unlink(apiFilePath);
    } catch (e) {
        // doesnt exist
    }
    // write a fake elm file with the repo url too

    await fs.promises.writeFile(
        path.join(OUTPUT_DIR, "LearningResources/Source.elm"),
        `module LearningResources.Source exposing (repoUrl)

{-| Generated by generate-elm-types.ts, do not edit
-}


repoUrl : String
repoUrl =
    "${REPO_URL}"
`
    );

    console.log(`Successfully generated Elm types in ${OUTPUT_DIR}/${MODULE_NAME}`);
}

generateElmTypes().catch(error => {
    console.error("Generation failed:", error);
    process.exit(1);
});
